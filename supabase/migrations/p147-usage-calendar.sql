-- supabase/migrations/p147-usage-calendar.sql (2026-11-10)
--
-- Feature backlog, push 16. Safe to run twice.
--
--   1. usage_events (audit T22, F11, decision: record only, no caps yet). One row per paid call: AI
--      tokens (Anthropic, Gemini), image renders, and transcription minutes. The app writes AI and
--      image rows with the service role; transcription rows come from a trigger on audio_tracks when
--      a track is marked done, which covers every provider (Groq in the sidecar, Replicate,
--      Deepgram) with no sidecar change. No personal data: rows name a campaign and session, not a
--      person, and both links are set to null if the campaign or session is deleted, so the totals
--      survive. GMs can read their own campaigns' rows; nobody can write them from the browser.
--   2. calendar_feeds + calendar_feed() (audit F8). Each account can have one secret calendar
--      address; calendar_feed(token) returns the scheduled sessions of every campaign the account
--      plays in or runs, for /api/calendar/<token>.ics. The token is the only key, like a private
--      calendar link, and can be replaced.
--   3. my_next_sessions() (audit F8): the next scheduled session per campaign, for the campaign cards.
--   4. my_campaigns() restated from the live definition (0000-base-schema.sql, unchanged since p3)
--      with two filters added: characters that left the table (active = false, audit F6) and
--      campaigns in the trash (deleted_at, p139) no longer list.

-- 1. usage ----------------------------------------------------------------------------------------

create table if not exists public.usage_events (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  campaign_id   uuid references public.campaigns(id) on delete set null,
  session_id    uuid references public.sessions(id) on delete set null,
  kind          text not null,
  provider      text,
  model         text,
  route         text,
  input_tokens  integer,
  output_tokens integer,
  images        integer,
  audio_seconds numeric
);

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'usage_events_kind_check') then
    alter table public.usage_events add constraint usage_events_kind_check
      check (kind in ('ai', 'image', 'transcription'));
  end if;
end $$;

create index if not exists usage_events_campaign_idx on public.usage_events (campaign_id, created_at);
create index if not exists usage_events_created_idx on public.usage_events (created_at);

alter table public.usage_events enable row level security;
-- Supabase grants new tables to anon and authenticated by default; say exactly what is meant.
revoke all on public.usage_events from anon, authenticated;
grant select on public.usage_events to authenticated;

drop policy if exists "gm reads campaign usage" on public.usage_events;
create policy "gm reads campaign usage" on public.usage_events for select to authenticated
  using (campaign_id is not null and public.is_campaign_gm(campaign_id));

-- A row written with only a session gets its campaign filled in.
create or replace function public.usage_events_fill_campaign()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.campaign_id is null and new.session_id is not null then
    select s.campaign_id into new.campaign_id from public.sessions s where s.id = new.session_id;
  end if;
  return new;
end $$;

drop trigger if exists usage_events_fill_campaign on public.usage_events;
create trigger usage_events_fill_campaign before insert on public.usage_events
  for each row execute function public.usage_events_fill_campaign();

-- Transcription minutes: a track turning done (from anything else) is one transcription. A track run
-- again after an error counts again, because it was paid for again.
create or replace function public.audio_tracks_usage()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_session uuid;
begin
  if new.status = 'done' and (old.status is distinct from 'done') then
    select j.session_id into v_session from public.capture_jobs j where j.id = new.job_id;
    insert into public.usage_events (campaign_id, session_id, kind, provider, model, route, audio_seconds)
    values (new.campaign_id, v_session, 'transcription',
            case when new.kind = 'room' then 'room' else 'speaker' end, null, 'audio_tracks', new.duration_seconds);
  end if;
  return new;
end $$;

drop trigger if exists audio_tracks_usage on public.audio_tracks;
create trigger audio_tracks_usage after update of status on public.audio_tracks
  for each row execute function public.audio_tracks_usage();

-- 2. calendar -------------------------------------------------------------------------------------

create table if not exists public.calendar_feeds (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  token      uuid not null unique default gen_random_uuid(),
  created_at timestamptz not null default now()
);

-- No policies and no grants: only the functions below touch it.
alter table public.calendar_feeds enable row level security;
revoke all on public.calendar_feeds from anon, authenticated;

create or replace function public.my_calendar_token()
returns uuid language plpgsql security definer set search_path = public as $$
declare v uuid;
begin
  if auth.uid() is null then raise exception 'not signed in'; end if;
  insert into public.calendar_feeds (profile_id) values (auth.uid()) on conflict (profile_id) do nothing;
  select token into v from public.calendar_feeds where profile_id = auth.uid();
  return v;
end $$;

create or replace function public.reset_my_calendar_token()
returns uuid language plpgsql security definer set search_path = public as $$
declare v uuid;
begin
  if auth.uid() is null then raise exception 'not signed in'; end if;
  insert into public.calendar_feeds (profile_id, token) values (auth.uid(), gen_random_uuid())
    on conflict (profile_id) do update set token = gen_random_uuid(), created_at = now()
    returning token into v;
  return v;
end $$;

-- Sessions scheduled from 30 days ago onward, in every campaign the token's account plays in (an
-- active player character) or runs, leaving out cancelled sessions and campaigns in the trash.
create or replace function public.calendar_feed(p_token uuid)
returns table (session_id uuid, campaign_id uuid, campaign_name text, session_number integer,
               scheduled_at timestamptz, status text, is_gm boolean)
language sql stable security definer set search_path = public as $$
  with me as (select profile_id from public.calendar_feeds where token = p_token),
  mine as (
    select c.id, c.name, (c.gm_id = (select profile_id from me)) as is_gm
      from public.campaigns c
     where c.deleted_at is null
       and (c.gm_id = (select profile_id from me)
            or exists (select 1 from public.characters ch
                        where ch.campaign_id = c.id and ch.profile_id = (select profile_id from me)
                          and ch.kind = 'pc' and coalesce(ch.active, true)))
  )
  select s.id, m.id, m.name, s.session_number, s.scheduled_at, s.status, m.is_gm
    from mine m join public.sessions s on s.campaign_id = m.id
   where exists (select 1 from me)
     and s.scheduled_at is not null
     and s.scheduled_at > now() - interval '30 days'
     and s.status in ('scheduled', 'live')
   order by s.scheduled_at
   limit 500;
$$;

revoke all on function public.calendar_feed(uuid) from public;
grant execute on function public.calendar_feed(uuid) to anon, authenticated;
revoke all on function public.my_calendar_token() from public, anon;
grant execute on function public.my_calendar_token() to authenticated;
revoke all on function public.reset_my_calendar_token() from public, anon;
grant execute on function public.reset_my_calendar_token() to authenticated;

-- 3. next sessions --------------------------------------------------------------------------------

create or replace function public.my_next_sessions()
returns table (campaign_id uuid, session_id uuid, session_number integer, scheduled_at timestamptz)
language sql stable security definer set search_path = public as $$
  select distinct on (s.campaign_id) s.campaign_id, s.id, s.session_number, s.scheduled_at
    from public.sessions s
    join public.campaigns c on c.id = s.campaign_id
   where c.deleted_at is null
     and s.status in ('scheduled', 'live')
     and s.scheduled_at is not null
     and s.scheduled_at > now() - interval '6 hours'
     and (c.gm_id = auth.uid()
          or exists (select 1 from public.characters ch
                      where ch.campaign_id = c.id and ch.profile_id = auth.uid()
                        and ch.kind = 'pc' and coalesce(ch.active, true)))
   order by s.campaign_id, s.scheduled_at;
$$;

revoke all on function public.my_next_sessions() from public, anon;
grant execute on function public.my_next_sessions() to authenticated;

-- 4. my_campaigns, live definition plus the two filters -------------------------------------------

CREATE OR REPLACE FUNCTION public.my_campaigns()
 RETURNS TABLE(campaign_id uuid, campaign_name text, system text, share_code text, gm_name text, my_characters bigint, last_session_at timestamp with time zone)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select
    c.id,
    c.name,
    c.system,
    c.share_code,
    coalesce(nullif(gm.display_name, ''), 'Your GM'),
    count(ch.id),
    (select max(s.started_at)
       from public.sessions s
      where s.campaign_id = c.id and s.started_at is not null)
  from public.characters ch
  join public.campaigns c  on c.id = ch.campaign_id
  left join public.profiles gm on gm.id = c.gm_id
  where ch.profile_id = auth.uid()
    and ch.kind = 'pc'
    and coalesce(ch.active, true)
    and c.deleted_at is null
  group by c.id, c.name, c.system, c.share_code, gm.display_name
  order by c.name;
$function$
;

