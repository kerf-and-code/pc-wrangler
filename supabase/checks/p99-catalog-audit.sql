select 'classes' as tbl, partner, count(*) from public.classes where partnered group by partner
union all
select 'species', partner, count(*) from public.species where partnered group by partner
union all
select 'class_capabilities', partner, count(*) from public.class_capabilities where partnered group by partner
order by 1, 2;

-- 5. Table shapes (columns and constraints) for the seed migration
select table_name, column_name, data_type, is_nullable, column_default
from information_schema.columns
where table_schema = 'public' and table_name in ('classes', 'species')
order by table_name, ordinal_position;
